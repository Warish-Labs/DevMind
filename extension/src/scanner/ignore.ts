export function isHardExcludedDirectory(dirName: string): boolean {
  return HARD_EXCLUDED_DIRECTORIES.has(dirName);
}

export function isCredentialPath(relPath: string): boolean {
  const baseName = path.basename(relPath);
  return CREDENTIAL_FILENAME_REGEX.test(baseName);
}

export function isGeneratedOrMinified(relPath: string, headerPrefix?: string): boolean {
  const baseName = path.basename(relPath);
  if (GENERATED_FILE_REGEX.test(baseName)) {
    return true;
  }
  if (headerPrefix) {
    const lower = headerPrefix.toLowerCase();
    if (
      lower.includes("@generated") ||
      lower.includes("generated by") ||
      lower.includes("do not edit")
    ) {
      return true;
    }
  }
  return false;
}

export function isBinaryExtension(relPath: string): boolean {
  const ext = path.extname(relPath).toLowerCase();
  return BINARY_EXTENSIONS.has(ext);
}

export function isBinaryContent(buffer: Buffer): boolean {
  // Sniff first 512 bytes for null byte (\0)
  const len = Math.min(buffer.length, 512);
  for (let i = 0; i < len; i++) {
    if (buffer[i] === 0) {
      return true;
    }
  }
  return false;
}

export function getLanguageMetadata(relPath: string): { id: string; tier: LanguageTier } {
  const ext = path.extname(relPath).toLowerCase();
  const matched = LANGUAGE_MAP[ext];
  if (matched) {
    return matched;
  }
  return { id: ext ? ext.slice(1) : "plaintext", tier: 3 };
}

/**
 * Lightweight gitignore/devmindignore pattern matcher conforming to git standard rules.
 */
export class IgnoreMatcher {
  private patterns: Array<{ regex: RegExp; negate: boolean }> = [];

  constructor(lines: string[] = []) {
    this.addPatterns(lines);
  }

  public addPatterns(lines: string[]): void {
    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line || line.startsWith("#")) {
        continue;
      }

      let negate = false;
      let pattern = line;
      if (pattern.startsWith("!")) {
        negate = true;
        pattern = pattern.slice(1);
      }

      // Convert gitignore glob pattern to RegExp
      const regex = this.globToRegex(pattern);
      if (regex) {
        this.patterns.push({ regex, negate });
      }
    }
  }

  public isIgnored(relPath: string): boolean {
    const normalized = relPath.replace(/\\/g, "/");
    let ignored = false;

    for (const { regex, negate } of this.patterns) {
      if (regex.test(normalized)) {
        ignored = !negate;
      }
    }

    return ignored;
  }

  private globToRegex(glob: string): RegExp | null {
    let p = glob;
    // Strip trailing slash but remember directory match
    const matchDirOnly = p.endsWith("/");
    if (matchDirOnly) {
      p = p.slice(0, -1);
    }

    // Escape regex special chars except * and ?
    let regexStr = p
      .replace(/[.+^${}()|[\]\\]/g, "\\$&")
      .replace(/\*\*/g, ".*")
      .replace(/(?<!\.)\*/g, "[^/]*")
      .replace(/\?/g, "[^/]");

    if (!p.startsWith("/")) {
      regexStr = "(?:^|/)" + regexStr;
    } else {
      regexStr = "^" + regexStr.slice(1);
    }

    if (matchDirOnly) {
      regexStr += "(?:/.*)?$";
    } else {
      regexStr += "(?:/.*)?$";
    }

    try {
      return new RegExp(regexStr);
    } catch {
      return null;
    }
  }
}
