"""RFC 9457 Problem Details error models and exception handlers."""

import logging
from typing import Any

from fastapi import Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

from app.core.logging import request_id_ctx

logger = logging.getLogger(__name__)

PROBLEM_MEDIA_TYPE = "application/problem+json"


class ProblemDetails(BaseModel):
    """RFC 9457 compliant problem details model per docs/03 §10."""

    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(description="A short, human-readable summary of the problem type.")
    status: int = Field(description="The HTTP status code generated by the origin server.")
    detail: str = Field(
        description="A human-readable explanation specific to this occurrence of the problem."
    )
    code: str = Field(description="DevMind stable machine-readable error code from docs/03 §10.1.")
    request_id: str | None = Field(default=None, description="Request ID correlation string.")
    errors: list[dict[str, Any]] | None = Field(
        default=None,
        description="Optional detailed field-level validation errors.",
    )


class DevMindError(Exception):
    """Base application exception mapping to an RFC 9457 Problem Details response."""

    def __init__(
        self,
        detail: str,
        code: str = "server.internal_error",
        status_code: int = 500,
        title: str = "Internal Server Error",
        errors: list[dict[str, Any]] | None = None,
        type_uri: str = "about:blank",
    ) -> None:
        super().__init__(detail)
        self.detail = detail
        self.code = code
        self.status_code = status_code
        self.title = title
        self.errors = errors
        self.type_uri = type_uri


