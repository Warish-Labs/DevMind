def _get_request_id(request: Request) -> str | None:
    return getattr(request.state, "request_id", None) or request_id_ctx.get()


async def devmind_error_handler(request: Request, exc: DevMindError) -> JSONResponse:
    """Handle all DevMind application errors with RFC 9457 Problem Details JSON."""
    req_id = _get_request_id(request)
    problem = ProblemDetails(
        type=exc.type_uri,
        title=exc.title,
        status=exc.status_code,
        detail=exc.detail,
        code=exc.code,
        request_id=req_id,
        errors=exc.errors,
    )
    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_MEDIA_TYPE,
    )


async def validation_error_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
    """Format FastAPI request validation errors into RFC 9457 Problem Details."""
    req_id = _get_request_id(request)
    formatted_errors = []
    for err in exc.errors():
        formatted_errors.append(
            {
                "location": ".".join(str(loc) for loc in err.get("loc", [])),
                "message": err.get("msg", "Invalid value"),
                "type": err.get("type", "value_error"),
            }
        )

    problem = ProblemDetails(
        type="about:blank",
        title="Validation Failed",
        status=422,
        detail="One or more request parameters failed validation",
        code="validation.failed",
        request_id=req_id,
        errors=formatted_errors,
    )
    return JSONResponse(
        status_code=422,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_MEDIA_TYPE,
    )


async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Handle unexpected server exceptions, logging the exception and returning RFC 9457."""
    req_id = _get_request_id(request)
    logger.exception("Unhandled server exception: %s", str(exc))

    problem = ProblemDetails(
        type="about:blank",
        title="Internal Server Error",
        status=500,
        detail="An internal server error occurred. Please retry later.",
        code="server.internal_error",
        request_id=req_id,
    )
    return JSONResponse(
        status_code=500,
        content=problem.model_dump(exclude_none=True),
        media_type=PROBLEM_MEDIA_TYPE,
    )
