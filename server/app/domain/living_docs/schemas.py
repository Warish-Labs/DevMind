"""Pydantic schemas for Living Documentation domain operations and REST APIs (docs/01 CAP-04, docs/03 §3.4)."""

from __future__ import annotations

from datetime import datetime
from typing import Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field


class DocRecordCreate(BaseModel):
    """Payload to register or update a tracked documentation file."""

    model_config = ConfigDict(extra="forbid")

    path: str = Field(min_length=1, max_length=512, description="Relative file path e.g. README.md")
    title: str = Field(min_length=1, max_length=255, description="Document display title")
    kind: str = Field(
        default="other",
        description="Classification: readme, api, architecture, tutorial, changelog, other",
    )
    content: str = Field(min_length=1, description="Raw Markdown content")
    file_id: UUID | None = Field(
        default=None, description="Optional Brain ProjectFile reference ID"
    )


class DocRecordResponse(BaseModel):
    """Summary of a tracked documentation record."""

    model_config = ConfigDict(from_attributes=True)

    id: UUID
    workspace_id: UUID
    project_id: UUID
    file_id: UUID | None
    path: str
    title: str
    kind: str
    current_version_hash: str
    last_parsed_at: datetime | None = None
    created_at: datetime
    updated_at: datetime


class DocRecordDetailResponse(DocRecordResponse):
    """Detailed view of a tracked documentation record including parsed symbols and drift count."""

    content_snapshot: str | None
    extracted_symbols: list[dict[str, Any]]
    drift_item_count: int = 0


class DocDriftDetectRequest(BaseModel):
    """Request payload to trigger DocsAlive drift detection for a project."""

    model_config = ConfigDict(extra="forbid")

    known_routes: list[str] = Field(
        default_factory=list,
        description="Active HTTP route paths in codebase e.g. ['GET /api/v1/projects', 'POST /api/v1/bugs']",
    )
    known_symbols: list[str] = Field(
        default_factory=list,
        description="Exported function, class, or interface symbol names e.g. ['BugMemoryService', 'DocParser']",
    )
    known_files: list[str] = Field(
        default_factory=list,
        description="List of active file paths in project repository",
    )
    known_configs: list[str] = Field(
        default_factory=list,
        description="Configuration environment variable names e.g. ['DATABASE_URL', 'REDIS_URL']",
    )


class PatchProposalResponse(BaseModel):
    """Proposed documentation patch generated by DocsAlive."""

    summary: str
    drift_kind: str
    target_section: str | None = None
    proposed_content: str
    diff_content: str | None = None
    gated: bool = True
    confidence: float = 0.85
    notes: list[str] = Field(default_factory=list)
    decided_by: str | None = None
    decided_at: str | None = None
    rejection_reason: str | None = None
    applied_at: str | None = None


class DocDriftItemResponse(BaseModel):
    """An identified discrepancy between project code and a documentation record."""

    model_config = ConfigDict(from_attributes=True)

    id: UUID
    workspace_id: UUID
    project_id: UUID
    documentation_record_id: UUID
    kind: str
    target_symbol_key: str | None
    target_route_path: str | None
    explanation: str
    status: str
    proposal: PatchProposalResponse | None = None
    created_at: datetime
    updated_at: datetime


class DocDriftDetectResponse(BaseModel):
    """Result of running DocsAlive drift detection."""

    project_id: UUID
    total_docs_analyzed: int
    drift_count: int
    drift_items: list[DocDriftItemResponse]
    summary: str


class DriftApprovalRequest(BaseModel):
    """Request body for human maintainer approval or rejection of a patch proposal."""

    model_config = ConfigDict(extra="forbid")

    reason: str | None = Field(
        default=None, description="Optional note or rationale for the decision"
    )


class DriftActionResponse(BaseModel):
    """Outcome of an approval, rejection, or application action on a drift item."""

    drift_id: UUID
    status: str
    message: str
    applied_patch_preview: str | None = None
